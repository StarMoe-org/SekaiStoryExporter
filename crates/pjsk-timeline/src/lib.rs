//! # pjsk-timeline — 时间轴编译器
//!
//! 把 IR 的相对语义编译成绝对时间轴。**这是节奏正确性的唯一负责方。**
//!
//! ## 职责
//! - Snippet 流 → 绝对秒数（`Delay` 语义、`Now` 并发、`WaitUntilFinished` 阻塞）
//! - 时长来源：语音实际时长 / 特效 Duration / 动作时长 / 无语音时的启发式
//! - 分支拍平（Q10 附带决策：默认走第一项，支持指定与全量）
//! - 支持人工覆盖文件（某句停顿加时等）
//!
//! ## 不负责
//! - 任何渲染或状态求值
//!
//! ## 允许依赖
//! `pjsk-core`、`pjsk-ir`、`pjsk-assets`。
